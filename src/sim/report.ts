// Turns a baseline record into a readable report, so the words can't drift from the numbers.
import type { Baseline } from "./baseline";

function table(headers: string[], rows: (string | number | null)[][]): string {
  const line = (cells: (string | number | null)[]) => `| ${cells.map((cell) => cell ?? "–").join(" | ")} |`;
  return [line(headers), line(headers.map(() => "---")), ...rows.map(line)].join("\n");
}

export function renderBaseline(baseline: Baseline): string {
  const { strategies, firstTrips, sustainedRoutes, recovery, investments, contracts, npcWorld, exploits } = baseline;
  const loop = exploits.samePortLoop;

  return `# Economy baseline (save version ${baseline.saveVersion})

The game's economy as it stood before Coins, measured by running the real rules with scripted players. Generated by \`npm run sim\`.

All amounts are in Coins.

## Strategies

Each ran on ${strategies[0].seeds} seeds, using only real commands. The game has no randomness of its own yet, so seeds only vary how a bot misjudges opportunities: strategies with no misjudgement play the same every time. A new game's net worth is ${baseline.newGameNetWorth}: starting Coins, starting cargo and the ship. Net worth uses the proposed formula: goods at 80% of base price, ships and upgrades at 60% of cost, property at 70%, plus Coins and route capital.

${table(
  ["Strategy", "Day", "Coins (min–median–max)", "Net worth", "Coins/day", "Net worth/voyage", "Net worth/real min", "Voyages", "Real min", "Rep.", "Ports"],
  strategies.flatMap((strategy) =>
    strategy.days.map((day) => [
      strategy.label,
      day.day,
      `${day.coins.min}–${day.coins.median}–${day.coins.max}`,
      day.netWorth.median,
      day.coinsPerDay,
      day.netWorthPerVoyage,
      day.netWorthPerRealMinute,
      day.voyages,
      day.realMinutes,
      day.reputation,
      day.portsVisited,
    ]),
  ),
)}

Real minutes count voyage time only, at 1× unless the strategy says otherwise. Thinking and tapping take longer.

### Market after 200 days, and what each strategy reached

${table(
  ["Strategy", "Price index", "Mean stock gap", "Near empty", "Near full", "NPC total worth", "Contracts", "Top route profit share", "Replays exactly", "Refused commands"],
  strategies.map((strategy) => {
    const day = strategy.days.at(-1)!;
    return [
      strategy.label,
      day.priceIndex,
      day.meanStockGap,
      day.stallsNearEmpty,
      day.stallsNearFull,
      day.npcTotalWorth,
      day.contractsDone,
      `${Math.round(strategy.topRouteProfitShare * 100)}%`,
      strategy.allRunsReplayExactly ? "Yes" : "**No**",
      strategy.refusedCommands,
    ];
  }),
)}

### Pacing: median day each thing first happened

A dash means most runs never got there within 200 days.

${table(
  ["Strategy", "Upgrade", "Extra ship", "Patello", "Route", "Warehouse", "Farm", "5 ports", "5 profit marks", "250 Coins"],
  strategies.map((strategy) => [
    strategy.label,
    strategy.firstDay.upgrade,
    strategy.firstDay.extraShip,
    strategy.firstDay.patello,
    strategy.firstDay.automatedRoute,
    strategy.firstDay.warehouse,
    strategy.firstDay.farm,
    strategy.firstDay.river_explorer,
    strategy.firstDay.trusted_trader,
    strategy.firstDay.prosperous_merchant,
  ]),
)}

## Routes

**First trip** is the best single cargo from fresh markets, for an empty base hold. It shows the temptation, not what lasts.

${table(
  ["Vessel", "Routes", "Profitable", "Best route", "Best good", "Profit", "Days", "Coins/day", "Top tenth", "Median", "Best ÷ top tenth"],
  firstTrips.map((summary) => [
    summary.vessel,
    summary.routes,
    summary.profitableRoutes,
    summary.best ? `${summary.best.from} → ${summary.best.to}` : null,
    summary.best?.good ?? null,
    summary.best?.profit ?? null,
    summary.best?.days ?? null,
    summary.best?.profitPerDay ?? null,
    summary.topTenthPerDay,
    summary.medianPerDay,
    summary.dominance,
  ]),
)}

**Sustained** is each of the ${sustainedRoutes.pairs} port pairs played as a real two-port loop for ${sustainedRoutes.days} days with a River boat. The top-tenth route earns ${sustainedRoutes.topTenthPerDay} Coins a day and the median ${sustainedRoutes.medianPerDay}. On ${sustainedRoutes.routesThatTire} routes the earnings fell by over 10% between the first third and the rest.

${table(
  ["Route", "Coins/day", "Later ÷ early earnings"],
  [...sustainedRoutes.best, ...sustainedRoutes.worst].map((route) => [
    `${route.first} ↔ ${route.second}`,
    route.coinsPerDay,
    route.lateVsEarly,
  ]),
)}

## Investments

- **Farm:** ${investments.farm.coinsPerDay} Coins a day from free rice at a median sale price, repaying in about ${investments.farm.paybackDays} days if collected in time. The farm player collected ${strategies.find((entry) => entry.id === "farming")!.farmUnitsCollected} rice in 200 days.

${table(
  ["Automated ship", "Price", "Route", "Capital start → end", "Coins/day", "Payback days"],
  investments.routeShips.map((ship) => [
    ship.vessel,
    ship.price,
    ship.route,
    `${ship.capitalStart} → ${ship.capitalEnd}`,
    ship.coinsPerDay,
    ship.paybackDays,
  ]),
)}

## Contracts

Priced at the starting market. "Worth doing" means the reward is more than the goods handed over.

${table(
  ["Type", "Count", "Average reward", "Average goods cost", "Worth doing"],
  contracts.map((entry) => [entry.type, entry.count, entry.averageReward, entry.averageGoodsCost, entry.worthDoing]),
)}

## Stock recovery

Each stall closes a share of the gap to its usual stock each day, at least one unit. Producers restock faster, and big buyers use up a surplus faster.

${table(
  ["Case", "Start", "Usual stock", "Days to halfway", "Days to full"],
  recovery.map((entry) => [entry.label, entry.startStock, entry.targetStock, entry.daysToHalfway, entry.daysToFull]),
)}

## Price impact of one hold

${table(
  ["Hold", "Stall", "Start price", "Last unit bought costs", "Last unit sold earns", "Lost buying and selling back"],
  baseline.marketImpact.map((entry) => [
    entry.hold,
    entry.stall,
    entry.startPrice,
    `+${Math.round(entry.buyRise * 100)}%`,
    `-${Math.round(entry.sellFall * 100)}%`,
    `${Math.round(entry.roundTripLossShare * 100)}%`,
  ]),
)}

## NPC merchants

${npcWorld.seeds} seeds, ${npcWorld.first.days} days with no player, one day at a time. The table shows the first seed.

${table(
  ["Merchant", "Start", "Day 30", "Day 90", "Day 200", "Trips", "Units sold", "Ports", "Profit/unit", "Last trade"],
  npcWorld.first.merchants.map((merchant) => [
    merchant.name,
    merchant.startWorth,
    merchant.worthAt[30],
    merchant.worthAt[90],
    merchant.worthAt[200],
    merchant.trips,
    merchant.unitsSold,
    merchant.portsVisited,
    merchant.profitPerUnit,
    merchant.lastTradeDay,
  ]),
)}

## Exploit checks

${table(
  ["Stock at Dhaka", ...loop.atLowStock.dhakaSilk.map((entry) => String(entry.stock))],
  [
    ["Silk: Coins per 100 loops", ...loop.atLowStock.dhakaSilk.map((entry) => entry.coinsPer100Loops)],
    ["Opium: Coins per 100 loops", ...loop.atLowStock.dhakaOpium.map((entry) => entry.coinsPer100Loops)],
  ],
)}

Cheapest stalls to bring into the loop from starting stock:

${table(
  ["Stall", "Start stock", "Pays at or below", "Units to buy", "Cost", "Coins per loop"],
  loop.cheapest.map((stall) => [
    `${stall.port} ${stall.good}`,
    stall.startStock,
    stall.profitableBelowStock,
    stall.unitsToDrain,
    stall.costToDrain,
    stall.profitPerLoop,
  ]),
)}

- **Closed time:** a voyage paused for 8 hours ends with the same game as one that wasn't: ${exploits.closedTimeChangesNothing ? "confirmed" : "**not confirmed**"}.
- **Replay:** every strategy run was rebuilt from its commands and compared exactly: ${strategies.every((strategy) => strategy.allRunsReplayExactly) ? "all match" : "**some differ**"}.

## What this can't tell us

- **City unlocks, seasons, weather, political events, pirates and voyage choices** don't exist yet, so their effect and pacing can't be measured. The only encounter is the Chittagong introduction.
- **Inflation** in the usual sense can't appear: prices depend only on stock, never on how much money exists. The market pays out without limit, which is the real risk.
- **Scripted players aren't people.** They're competent, not optimal, and a skilled player may do better. They can't show what's fun, clear or tedious.
- **Activity levels** only change real time, since closed time counts for nothing. Casual and active players differ here in judgement and speed, not in what the world does.
- **Farm-heavy play** is limited to 6 farms and to the ports the bot happens to pass. All 15 weren't tried.
- **Warehouses** were tested on one route with one simple rule. A cleverer plan might do better.
- **Real phones:** none of this says anything about performance on a device.
`;
}
